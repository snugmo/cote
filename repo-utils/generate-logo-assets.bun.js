#!/usr/bin/env bun
// Regenerates all logo artifacts from the source of truth:
//   logo-explorations/molecule-capsule.svg   ("The Bond")
//
// Outputs:
//   logo-explorations/preview-data.js         inlined SVGs for preview.html (accent -> var(--accent))
//   logo-explorations/final/bond.svg          dynamic: light ink + @media (prefers-color-scheme: dark)
//   logo-explorations/final/bond-light.svg    static: dark ink, for light backgrounds
//   logo-explorations/final/bond-dark.svg     static: light ink, for dark backgrounds
//   assets/bond*.svg                          copies of the final set at the repo root
//
// Notes:
//   - The dynamic file deliberately avoids CSS var(): librsvg (rsvg-convert) does not
//     support var(), but class rules + media queries work there and in browsers.
//   - rsvg-convert always evaluates prefers-color-scheme as false, so use
//     bond-light.svg / bond-dark.svg for fixed-scheme CLI rendering.
//
// Usage:  bun repo-utils/generate-logo-assets.bun.js
import { readFileSync, readdirSync, writeFileSync, mkdirSync, copyFileSync, rmSync } from "fs";
import { dirname, join } from "path";
import { fileURLToPath } from "url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const explore = join(root, "logo-explorations");
const finalDir = join(explore, "final");
const assetsDir = join(root, "assets");

const ACCENT = "#f472b6";
const INK_LIGHT = "#1f2328";
const INK_DARK = "#e6edf3";
const HEADER = '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 256 256">';

// ---- 1) preview gallery data: every mark, accent as a live CSS var ----
const preview = {};
for (const f of readdirSync(explore).filter((f) => f.endsWith(".svg")).sort()) {
  preview[f] = readFileSync(join(explore, f), "utf8").replaceAll("#0ea5a0", "var(--accent)");
}
writeFileSync(
  join(explore, "preview-data.js"),
  `// generated by repo-utils/generate-logo-assets.bun.js — do not edit\nwindow.MARK_SVGS = ${JSON.stringify(preview, null, 1)};\n`,
);

// ---- 2) the final Bond set, from the source mark ----
const src = readFileSync(join(explore, "molecule-capsule.svg"), "utf8").replaceAll("#0ea5a0", ACCENT);

// dynamic: literal light-ink strokes + class, media query for dynamic renderers
const style = `  <style>
    /* Default (light) ink; librsvg and other non-dynamic renderers stop here. */
    .ink { stroke: ${INK_LIGHT}; }
    /* Dynamic renderers (browsers) follow the system scheme. */
    @media (prefers-color-scheme: dark) { .ink { stroke: ${INK_DARK}; } }
  </style>
`;
const dynamic = src
  .replaceAll('stroke="currentColor"', `class="ink" stroke="${INK_LIGHT}"`)
  .replace(HEADER, `${HEADER} role="img" aria-label="The Bond — terminal and agent inside a workspace">\n${style}`);

writeFileSync(join(finalDir, "bond.svg"), dynamic);
writeFileSync(join(finalDir, "bond-light.svg"), src.replaceAll('stroke="currentColor"', `stroke="${INK_LIGHT}"`));
writeFileSync(join(finalDir, "bond-dark.svg"), src.replaceAll('stroke="currentColor"', `stroke="${INK_DARK}"`));

// ---- 3) repo-root assets: copies of the final set ----
rmSync(assetsDir, { recursive: true, force: true });
mkdirSync(assetsDir, { recursive: true });
for (const f of ["bond.svg", "bond-light.svg", "bond-dark.svg"]) {
  copyFileSync(join(finalDir, f), join(assetsDir, f));
}

console.log("regenerated: preview-data.js (", Object.keys(preview).length, "marks), final/bond*.svg, assets/bond*.svg");
